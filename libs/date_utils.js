// สั่งส่งออกโมดูลก้อนนี้ (object) เพื่อให้ไฟล์อื่นสามารถดึงฟังก์ชันไปใช้งานได้
module.exports = {
  
  // สร้างฟังก์ชันชื่อ getCurrentDateForToken เพื่อทำหน้าที่จัดรูปแบบวันที่สำหรับเอาไปฝังในตั๋ว Token
  getCurrentDateForToken: () => {
    
    // บรรทัดนี้คือการดึงวันและเวลาปัจจุบันของโลก ณ วินาทีนี้ จากเครื่องคอมพิวเตอร์มาเก็บไว้ในตัวแปร now
    const now = new Date();
    
    // ตั้งค่าการแปลงรูปแบบวันที่ให้เป็นสไตล์สากล 'en-GB' (คือเรียงแบบ วัน/เดือน/ปี ค.ศ.) 
    // โดยกำหนดให้ วัน (day) และ เดือน (month) ต้องแสดงเป็นเลข 2 หลักเสมอ (เช่น 01, 02)
    const formattedDate = new Intl.DateTimeFormat('en-GB', {
      day: '2-digit',
      month: '2-digit',
      year: 'numeric'
    })
    .format(now) // สั่งให้นำค่าเวลาในตัวแปร now มาจับยัดใส่รูปแบบที่เราตั้งค่าไว้ด้านบน (จะได้ผลลัพธ์หน้าตาประมาณ "11/07/2026")
    .replace(/\//g, '-'); // บรรทัดนี้คือคำสั่งค้นหาเครื่องหมายสแลช ( / ) ทั้งหมด แล้วเปลี่ยนให้เป็นเครื่องหมายขีดกลาง ( - ) แทน (จาก "11/07/2026" จะกลายเป็น "11-07-2026")

    // ส่งผลลัพธ์วันที่ที่จัดรูปแบบเสร็จสรรพเรียบร้อยแล้ว (เช่น "11-07-2026") ออกไปให้คนที่เรียกใช้ฟังก์ชันนี้เอาไปใช้งานต่อ
    return formattedDate;
  }
}
//ฟังก์ชันนี้มีหน้าที่สั้น ๆ คือ "เปลี่ยนวันปัจจุบันในคอมพิวเตอร์ ให้กลายเป็นข้อความวันที่แบบมีขีดกลาง" เช่น จากเดิมที่ระบบมองเป็นเวลายุ่งเหยิง 
// ฟังก์ชันนี้จะจัดระเบียบและตบแต่งหน้าตาให้ออกมาเป็นข้อความนิ่ง ๆ
//  ลื่นตาอย่าง 11-07-2026 เพื่อให้ระบบหลังบ้านหยิบข้อความตัวนี้ไปปั๊มตราฝังลงไปในตั๋วล็อกอิน (Token) ได้อย่างสวยงามและเป็นระเบียบ