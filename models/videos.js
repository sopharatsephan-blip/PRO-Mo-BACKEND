const pool = require('../libs/db_pool'); // ดึงไฟล์อ่างเก็บสายเชื่อมต่อฐานข้อมูลที่เราตั้งค่าไว้เข้ามาใช้งานในไฟล์นี้

module.exports = { // สั่งส่งออกกลุ่มฟังก์ชันภายในก้อนนี้ เพื่อให้ไฟล์อื่น (เช่น controller หรือ server.js) ดึงไปใช้งานได้
    getAllVideosByUser: async (uid) => { // สร้างฟังก์ชันดึงวิดีโอทั้งหมดตามรหัสผู้ใช้ โดยรับรหัสคนใช้ (uid) เข้ามา
        let conn; // เตรียมสร้างกล่องเปล่าชื่อ conn เอาไว้สำหรับรอใส่สายเชื่อมต่อฐานข้อมูล
        let result; // เตรียมสร้างกล่องเปล่าชื่อ result เอาไว้สำหรับรอเก็บก้อนผลลัพธ์ที่จะส่งกลับไปหน้าบ้าน

        try { // เริ่มต้นบล็อก try (แปลว่า "ลองทำตามคำสั่งในนี้ดูนะ") ถ้าทำงานราบรื่นดีจะทำจนเสร็จสิ้น
            conn = await pool.getConnection(); // สั่งให้ไปหยิบสายเชื่อมต่อฐานข้อมูลที่ว่างอยู่จากอ่าง pool มาเก็บไว้ใน conn

            // เขียนคำสั่ง SQL: ดึงรหัสวิดีโอ, ชื่องาน, ที่อยู่ไฟล์, วันที่อัปโหลด (จัดฟอร์แมต), จำนวนผู้ชม, ชื่อบริษัท และชื่อสถานะวิดีโอ
            var sql = "SELECT v.VideoID, v.VideoTitle, v.VideoPath, "
                    + "DATE_FORMAT(v.UploadDate, '%d-%m-%Y') AS UploadDate, " // สั่งจัดรูปแบบวันที่จากฐานข้อมูลให้ออกมาเป็น วัน-เดือน-ปี
                    + "v.ViewCount, c.CompanyName, s.StatusName "
                    + "FROM Video v " // ระบุว่าให้ดึงข้อมูลจากตารางหลักที่ชื่อ Video (โดยตั้งชื่อเล่นสั้น ๆ ว่า v)
                    + "INNER JOIN Company c ON v.CompanyID = c.CompanyID " // สั่งให้เอาตาราง Company (ชื่อเล่น c) มารวมร่างกัน โดยจับคู่ตรงรหัสบริษัทที่ตรงกัน
                    + "INNER JOIN VideoStatus s ON v.VideoStatusID = s.VideoStatusID " // สั่งให้เอาตาราง VideoStatus (ชื่อเล่น s) มารวมร่างกัน โดยจับคู่ตรงรหัสสถานะที่ตรงกัน
                    + "WHERE v.UID = ? " // กำหนดเงื่อนไขว่า "จะดึงมาเฉพาะข้อมูลของรหัสผู้ใช้ (UID) ที่ตรงกับเครื่องหมาย ? เท่านั้น"
                    + "ORDER BY v.UploadDate DESC"; // เรียงลำดับจากวันที่อัปโหลดล่าสุดลงไป

            var rows = await conn.query(sql, [uid]); // สั่งรันคำสั่ง SQL ด้านบน โดยเอาค่า uid ที่รับมา ไปหยอดแทนที่เครื่องหมาย ? 

            result = { // มัดก้อนผลลัพธ์ใส่กล่อง result เมื่อรันคำสั่งดึงข้อมูลได้สำเร็จเรียบร้อย
                isError: false, // บอกหน้าบ้านว่า "ไม่พบข้อผิดพลาดจ้า"
                data: rows, // แนบก้อนข้อมูลแถวรายการวิดีโอทั้งหมดที่ดึงได้จากฐานข้อมูลส่งไปให้หน้าบ้าน
                errorMessage: "" // ช่องข้อความแจ้งเตือนข้อผิดพลาดปล่อยให้ว่างไว้ เพราะทำงานผ่านฉลุย
            };

        } catch (error) { // บล็อก catch จะทำงานทันทีถ้าเกิดเหตุการณ์ระบบพัง หรือฐานข้อมูลมีปัญหาในบล็อก try
            result = { // มัดก้อนผลลัพธ์รูปแบบแจ้งเตือนความผิดพลาดใส่กล่อง result แทน
                isError: true, // บอกหน้าบ้านชัดเจนเลยว่า "อุ๊ย! เกิดข้อผิดพลาดขึ้นแล้วนะ"
                data: "", // ข้อมูลส่งกลับปล่อยเป็นค่าว่างไว้ เพราะดึงข้อมูลมาไม่ได้
                errorMessage: error.message // ส่งข้อความสาเหตุที่พัง (เช่น เชื่อมฐานข้อมูลไม่ได้) ไปให้หน้าบ้านอ่านดู
            };
        } finally { // บล็อกสุดท้าย finally จะทำงานเสมอ 100% ไม่ว่าระบบจะรันผ่านหรือรันพังก็ตาม
            if (conn) // เช็กดูว่าถ้าในกล่อง conn มีสายเชื่อมต่อค้างอยู่จริง ๆ
                conn.release(); // สั่งตัดสายปล่อยวาง แล้วคืนสายกลับเข้าอ่าง pool ทันที เพื่อไม่ให้ระบบค้างและกินแรม
        }

        return result; // ส่งก้อนผลลัพธ์สุดท้าย (ไม่ว่าจะสำเร็จหรือพัง) ในกล่อง result กลับคืนไปให้คนที่เรียกใช้ฟังก์ชันนี้
    }
};