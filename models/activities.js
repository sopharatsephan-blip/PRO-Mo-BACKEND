//2.ใช้คำสั่ง JOIN เพื่อเปิดคลังเอา "ตารางกิจกรรม" มารวมร่างกับ "ตารางชื่อท่าออกกำลังกาย" จะได้รู้ว่ากิจกรรมนั้นคือท่าอะไร

//3.กรองคัดเลือกมาเฉพาะกิจกรรมของคน ๆ นั้น (WHERE account_id = ?)ปรับหน้าตาวันที่ให้เรียงสวยงามอ่านง่ายด้วย DATE_FORMAT แล้วมัดใส่ถุงส่งไปให้หน้าบ้านใช้งานอย่างปลอดภัยค่ะ